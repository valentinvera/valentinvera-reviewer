#!/bin/sh
# Render a CONNECT-only Squid config. Names come from a file, one per line.
# The proxy never decrypts TLS and does not log request paths.
set -eu

bind=""
src=""
allow_file=""
fixture_name=""
fixture_dst=""

while [ $# -gt 0 ]; do
  case "$1" in
    --bind) bind="$2"; shift 2 ;;
    --src) src="$2"; shift 2 ;;
    --allow-file) allow_file="$2"; shift 2 ;;
    --fixture-name) fixture_name="$2"; shift 2 ;;
    --fixture-dst) fixture_dst="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 1 ;;
  esac
done

case "$bind" in
  172.30.208.2:3128|172.30.209.2:3128|172.30.210.2:3128) ;;
  *) echo "refusing PROXY bind $bind" >&2; exit 1 ;;
esac

case "$src" in
  172.30.208.0/24|172.30.209.0/24|172.30.210.0/24) ;;
  *) echo "refusing PROXY source $src" >&2; exit 1 ;;
esac

if [ -z "$allow_file" ] || [ ! -f "$allow_file" ]; then
  echo "allowlist file is required" >&2
  exit 1
fi

names=$(awk '
  /^[[:space:]]*#/ { next }
  /^[[:space:]]*$/ { next }
  {
    name = $1
    if (name !~ /^[A-Za-z0-9.-]+$/) {
      print "invalid allowlist name" > "/dev/stderr"
      exit 2
    }
    if (name ~ /^[0-9.]+$/) {
      print "IP literals are not allowlist names" > "/dev/stderr"
      exit 2
    }
    print name
  }
' "$allow_file") || exit 1

if [ -z "$names" ]; then
  echo "allowlist is empty" >&2
  exit 1
fi

if [ -n "$fixture_name" ] || [ -n "$fixture_dst" ]; then
  if [ -z "$fixture_name" ] || [ -z "$fixture_dst" ]; then
    echo "fixture name and destination must be set together" >&2
    exit 1
  fi
  case "$fixture_dst" in
    172.30.217.10/32|172.30.218.10/32) ;;
    *) echo "refusing fixture destination $fixture_dst" >&2; exit 1 ;;
  esac
fi

cat <<EOF
# Generated by render-squid-conf.sh. Do not put secrets in this file.
# CONNECT tunnels only. TLS stays end to end. No URL-path log.
pid_filename /var/run/squid/squid.pid
coredump_dir /tmp
cache deny all
cache_mem 8 MB
access_log none
cache_store_log none
logfile_rotate 0
via off
forwarded_for delete
httpd_suppress_version_string on
# Quiet tunnel time. The deployed model deadline is 10 minutes and the
# application cap is 30 minutes. 35 minutes covers that cap plus setup.
read_timeout 35 minutes
client_lifetime 12 hours
connect_timeout 30 seconds
request_timeout 1 minute

http_port ${bind}

acl app_net src ${src}
acl SSL_ports port 443
acl CONNECT method CONNECT
EOF

printf '%s\n' "$names" | while IFS= read -r name; do
  printf 'acl allowed dstdomain %s\n' "$name"
done

cat <<'EOF'
acl ip_literal dstdom_regex -i ^[0-9]{1,3}(\.[0-9]{1,3}){3}$
acl ip_literal dstdom_regex -i ^\[
acl bogon dst 0.0.0.0/8
acl bogon dst 10.0.0.0/8
acl bogon dst 100.64.0.0/10
acl bogon dst 127.0.0.0/8
acl bogon dst 169.254.0.0/16
acl bogon dst 172.16.0.0/12
acl bogon dst 192.0.0.0/24
acl bogon dst 192.0.2.0/24
acl bogon dst 192.168.0.0/16
acl bogon dst 198.18.0.0/15
acl bogon dst 198.51.100.0/24
acl bogon dst 203.0.113.0/24
acl bogon dst 224.0.0.0/4
acl bogon dst 240.0.0.0/4
acl bogon dst ::/128
acl bogon dst ::1/128
acl bogon dst fc00::/7
acl bogon dst fe80::/10
acl bogon dst ff00::/8

http_access deny !app_net
http_access deny !CONNECT
http_access deny CONNECT !SSL_ports
http_access deny ip_literal
EOF

if [ -n "$fixture_name" ]; then
  cat <<EOF
# Test-only exception so a local fixture on this subnet can hold a quiet tunnel.
acl fixture_name dstdomain ${fixture_name}
acl fixture_dst dst ${fixture_dst}
http_access allow CONNECT fixture_name fixture_dst
EOF
fi

cat <<'EOF'
http_access deny bogon
http_access allow CONNECT allowed
http_access deny all
EOF
